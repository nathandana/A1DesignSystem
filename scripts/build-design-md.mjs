#!/usr/bin/env node
import fs from 'node:fs';
import { stringify } from 'yaml';
import { parseTokens } from '../packages/mcp-server/scripts/lib/parse-tokens.mjs';
import { repoPath } from '../packages/mcp-server/scripts/lib/paths.mjs';

// Read the same resolved Style Dictionary values as the MCP index.
const tokens = new Map(parseTokens().map(token => [token.path, token.value]));
const sources = new Map();
function value(path) {
  if (!tokens.has(path)) throw new Error(`Missing design token: ${path}`);
  sources.set(path, tokens.get(path));
  return tokens.get(path);
}
const scale = (prefix, names) => Object.fromEntries(names.map(name => [name, value(`${prefix}.${name}`)]));
const typography = (role, size) => ({
  fontFamily: value(`base.font.family.${role}`),
  fontSize: value(`semantic.font.size.${role}.${size}`),
  fontWeight: value(`semantic.font.weight.${role}`),
  lineHeight: value(`semantic.font.lineHeight.${role}`),
});
const frontmatter = {
  version: 'alpha',
  name: 'A1',
  description: 'Component-first interfaces with clear hierarchy, restrained surfaces and accessible interaction.',
  colors: {
    primary: value('component.button.primary.background'),
    'on-primary': value('component.button.primary.foreground'),
    ink: value('semantic.color.text.default'),
    page: value('semantic.color.surface.page'),
    panel: value('semantic.color.surface.panel'),
  },
  typography: { 'body-md': typography('body', 'md'), h1: typography('heading', 'xxl'), h2: typography('heading', 'md') },
  rounded: scale('base.radius', ['sm', 'md', 'lg', 'xl']),
  spacing: scale('semantic.spacing.gap', ['xs', 'sm', 'md', 'lg', 'xl']),
  components: {
    'button-primary': { backgroundColor: '{colors.primary}', textColor: '{colors.on-primary}', rounded: '{rounded.md}' },
    page: { backgroundColor: '{colors.page}', textColor: '{colors.ink}', typography: '{typography.body-md}' },
    'page-title': { backgroundColor: '{colors.panel}', textColor: '{colors.ink}', typography: '{typography.h1}' },
  },
};
const ranges = ['xs', 'sm', 'md', 'lg', 'xl'].map(name => {
  const min = tokens.has(`breakpoint.${name}.min`) ? value(`breakpoint.${name}.min`) : '0';
  const max = tokens.has(`breakpoint.${name}.max`) ? value(`breakpoint.${name}.max`) : 'and above';
  return `| ${name} | ${max === 'and above' ? `${min} and above` : `${min}–${max}`} |`;
}).join('\n');
const body = fs.readFileSync(repoPath('packages/react/ai/design-md-body.md'), 'utf8')
  .replace('<!-- BREAKPOINTS -->', ranges);
const provenance = [...sources].map(([path, resolved]) => `| \`${path}\` | \`${resolved}\` |`).join('\n');
const output = `---\n${stringify(frontmatter)}---\n\n<!-- Generated by npm run build:design-md. Edit source tokens and packages/react/ai/design-md-body.md. -->\n\n${body.trim()}\n\n### Token provenance\n\nThe values above describe the default light appearance. Theme and mode overrides remain authoritative at runtime. This is a selected design vocabulary, not the full token registry.\n\n| A1 token | Resolved value |\n| --- | --- |\n${provenance}\n`;
let stale = false;
const artifacts = [
  ['design.md', output],
  ['apps/a1-web/public/design.md', output],
  ['apps/a1-web/public/react-setup.md', fs.readFileSync(repoPath('packages/react/guidelines/setup.md'), 'utf8')],
  ['apps/a1-web/public/a1-agent-brief.md', fs.readFileSync(repoPath('packages/react/ai/a1-agent-brief.md'), 'utf8')],
];
for (const [file, content] of artifacts) {
  const target = repoPath(file);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
      console.error(`${file} is stale. Run npm run build:tokens && npm run build:design-md.`);
      stale = true;
    }
  } else {
    fs.mkdirSync(new URL('../apps/a1-web/public/', import.meta.url), { recursive: true });
    fs.writeFileSync(target, content);
    console.log(`Wrote ${file}`);
  }
}
if (stale) process.exitCode = 1;
