#!/usr/bin/env node
/**
 * build-eslint-rules — keeps `eslint-plugin-a1` in sync with the design rules.
 *
 * The YAML in `system/rules/*.yaml` is the single source of truth. A rule that should be
 * enforced on code carries an `enforcement.eslint: <rule-name>` (and optional `css: true`).
 * This script:
 *   1. reads every YAML rule with `enforcement.eslint`,
 *   2. writes `packages/eslint-plugin-a1/lib/generated/rule-meta.js` — the YAML spec
 *      (requirement / do / dont / appliesTo / file) keyed by ESLint rule name, which the
 *      plugin overlays onto each rule's `meta.docs` so the lint message links back to the rule,
 *   3. validates the mapping is 1:1 — every `enforcement.eslint` has an implemented rule file
 *      and every rule file is claimed by exactly one YAML rule — and exits non-zero on drift.
 *
 * Run with `--check` in CI to fail if the committed generated file is stale (no write).
 *
 * Usage: node scripts/build-eslint-rules.mjs [--check]
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { parse as parseYaml } from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rulesDir = join(root, 'system', 'rules');
const pluginRulesDir = join(root, 'packages', 'eslint-plugin-a1', 'lib', 'rules');
const generatedFile = join(root, 'packages', 'eslint-plugin-a1', 'lib', 'generated', 'rule-meta.js');

const check = process.argv.includes('--check');
const errors = [];

// ── 1. Collect enforcement metadata from the YAML ────────────────────────────
const byEslintRule = {};
const cssRules = [];
for (const file of readdirSync(rulesDir).filter((f) => f.endsWith('.yaml'))) {
  let doc;
  try { doc = parseYaml(readFileSync(join(rulesDir, file), 'utf8')); }
  catch (e) { errors.push(`Cannot parse system/rules/${file}: ${e.message}`); continue; }
  for (const r of doc?.rules ?? []) {
    const enf = r?.enforcement;
    if (!enf) continue;
    const meta = {
      id: r.id,
      file,
      requirement: r.requirement ?? '',
      do: r.do ?? '',
      dont: r.dont ?? '',
      appliesTo: Array.isArray(r.applies_to) ? r.applies_to : [],
      css: enf.css === true,
    };
    if (enf.eslint) {
      if (byEslintRule[enf.eslint]) {
        errors.push(`Two YAML rules claim ESLint rule "${enf.eslint}": ${byEslintRule[enf.eslint].id} and ${r.id}`);
      }
      byEslintRule[enf.eslint] = meta;
    }
    if (enf.css === true) cssRules.push(meta);
  }
}

// ── 2. Cross-check against implemented plugin rules ──────────────────────────
const implemented = new Set(
  existsSync(pluginRulesDir)
    ? readdirSync(pluginRulesDir).filter((f) => f.endsWith('.js')).map((f) => f.replace(/\.js$/, ''))
    : [],
);
for (const name of Object.keys(byEslintRule)) {
  if (!implemented.has(name)) {
    errors.push(`YAML enforces ESLint rule "${name}" (rule ${byEslintRule[name].id}) but packages/eslint-plugin-a1/lib/rules/${name}.js does not exist.`);
  }
}
for (const name of implemented) {
  if (!byEslintRule[name]) {
    errors.push(`Plugin rule "${name}.js" has no YAML rule pointing at it (add enforcement.eslint: ${name} to a system/rules/*.yaml rule).`);
  }
}

// ── 3. Generate the rule-meta module ─────────────────────────────────────────
const sorted = Object.fromEntries(Object.keys(byEslintRule).sort().map((k) => [k, byEslintRule[k]]));
const banner = '// @generated by scripts/build-eslint-rules.mjs from system/rules/*.yaml — do not edit by hand.\n'
  + '// Run `npm run build:eslint-rules` to refresh.\n';
const content = `${banner}export const ruleMeta = ${JSON.stringify(sorted, null, 2)};\n`;

if (errors.length) {
  console.error('✖ eslint-plugin-a1 ↔ system/rules drift:\n' + errors.map((e) => `  - ${e}`).join('\n'));
  process.exit(1);
}

if (check) {
  const current = existsSync(generatedFile) ? readFileSync(generatedFile, 'utf8') : '';
  if (current !== content) {
    console.error('✖ packages/eslint-plugin-a1/lib/generated/rule-meta.js is stale. Run `npm run build:eslint-rules` and commit.');
    process.exit(1);
  }
  console.log(`✓ eslint-plugin-a1 rule metadata in sync (${Object.keys(sorted).length} enforced rules, ${cssRules.length} with a CSS arm).`);
} else {
  mkdirSync(dirname(generatedFile), { recursive: true });
  writeFileSync(generatedFile, content);
  console.log(`✓ Wrote rule metadata for ${Object.keys(sorted).length} enforced ESLint rules (${cssRules.length} also enforced in CSS).`);
}
