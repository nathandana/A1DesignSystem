import test from 'node:test'
import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
const origin = process.env.LABS_ORIGIN ?? 'http://127.0.0.1:5187'

test('magnetic reordering supports preview, cancellation, placement, undo and still motion', async () => {
  const browser = await chromium.launch()
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage()
    const errors = []; page.on('pageerror', e => errors.push(e.message))
    await page.goto(`${origin}/experiments/reordering`)
    await page.getByRole('radio', { name: 'Magnetic drag and drop', exact: true }).press('Space')
    const grid = page.locator('.a1-magnetic-reorder'), tiles = grid.locator('[data-item]')
    const order = () => tiles.evaluateAll(nodes => nodes.map(node => node.dataset.item))
    const original = ['discover', 'sketch', 'prototype', 'test', 'ship']
    const handle = grid.getByRole('button', { name: 'Move Discover', exact: true })
    await handle.press('Space'); await handle.press('End')
    await expect(grid.getByText('Drop here · 5')).toBeVisible()
    assert.deepEqual(await order(), ['sketch', 'prototype', 'test', 'ship', 'discover'])
    await handle.press('Escape'); assert.deepEqual(await order(), original)
    await expect(handle).toBeFocused()
    await handle.press('Space'); await handle.press('ArrowRight'); await handle.press('Space')
    assert.deepEqual(await order(), ['sketch', 'discover', 'prototype', 'test', 'ship'])
    await grid.getByRole('button', { name: 'Undo', exact: true }).click()
    assert.deepEqual(await order(), original)
    await grid.evaluate(el => el.getAnimations({ subtree: true }).forEach(a => a.finish()))
    const start = await handle.boundingBox(), a = await tiles.nth(0).boundingBox(), b = await tiles.nth(1).boundingBox()
    await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2); await page.mouse.down()
    await page.mouse.move(start.x + start.width / 2 + b.x - a.x, start.y + start.height / 2 + b.y - a.y, { steps: 8 })
    await expect(grid.getByText('Drop here · 2')).toBeVisible()
    await expect(page.locator('.a1-magnetic-reorder__ghost')).toHaveCount(1)
    await page.mouse.up()
    assert.deepEqual(await order(), ['sketch', 'discover', 'prototype', 'test', 'ship'])
    await expect(page.locator('.a1-magnetic-reorder__ghost')).toHaveCount(0)
    await grid.getByRole('button', { name: 'Undo', exact: true }).click()
    await grid.evaluate(el => el.getAnimations({ subtree: true }).forEach(a => a.finish()))
    const cancelStart = await handle.boundingBox()
    await page.mouse.move(cancelStart.x + cancelStart.width / 2, cancelStart.y + cancelStart.height / 2); await page.mouse.down()
    await page.mouse.move(1100, 920)
    await expect(grid.getByText('No target')).toBeVisible()
    await page.mouse.up(); assert.deepEqual(await order(), original)
    await handle.press('Space'); await handle.press('End')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await expect.poll(() => tiles.evaluateAll(nodes => nodes.flatMap(el => el.getAnimations()).length)).toBe(0)
    await grid.getByRole('button', { name: 'Cancel move', exact: true }).click()
    assert.deepEqual(await order(), original)
    const results = await new AxeBuilder({ page }).include('.a1-magnetic-reorder').disableRules(['color-contrast']).analyze()
    assert.deepEqual(results.violations, [])
    await page.screenshot({ path: '/tmp/labs-magnetic-desktop.png' })
    await page.setViewportSize({ width: 390, height: 900 })
    assert.equal(await grid.locator('[role=list]').evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length), 2)
    assert.ok(await grid.evaluate(el => el.getBoundingClientRect().right <= innerWidth))
    await handle.press('Space'); await handle.press('ArrowDown')
    await expect(grid.getByText('Drop here · 3')).toBeVisible()
    await handle.press('Escape')
    await page.screenshot({ path: '/tmp/labs-magnetic-mobile.png' })
    assert.deepEqual(errors, [])
  } finally { await browser.close() }
})

test('touch dragging and forced colors retain the landing preview and committed order', async () => {
  const browser = await chromium.launch()
  try {
    const context = await browser.newContext({ hasTouch: true, viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage()
    await page.goto(`${origin}/experiments/reordering`)
    await page.getByRole('radio', { name: 'Magnetic drag and drop', exact: true }).press('Space')
    await page.setViewportSize({ width: 390, height: 900 })
    await page.emulateMedia({ reducedMotion: 'reduce', forcedColors: 'active' })
    const grid = page.locator('.a1-magnetic-reorder'), tiles = grid.locator('[data-item]')
    await grid.getByRole('button', { name: 'Move Discover', exact: true }).click({ trial: true })
    const handle = await grid.getByRole('button', { name: 'Move Discover', exact: true }).boundingBox()
    const first = await tiles.nth(0).boundingBox(), second = await tiles.nth(1).boundingBox()
    const client = await context.newCDPSession(page)
    const point = { x: handle.x + handle.width / 2, y: handle.y + handle.height / 2 }
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [point] })
    await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: point.x + second.x - first.x, y: point.y + second.y - first.y }] })
    await expect(grid.getByText('Drop here · 2')).toBeVisible()
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect(tiles.nth(1)).toHaveAttribute('data-item', 'discover')
    await expect(page.locator('.a1-magnetic-reorder__ghost')).toHaveCount(0)
    await page.goto(`${origin}/about`)
    await expect(page.locator('.a1-magnetic-reorder__ghost')).toHaveCount(0)
  } finally { await browser.close() }
})
