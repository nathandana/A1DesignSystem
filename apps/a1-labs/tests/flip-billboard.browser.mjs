import test from 'node:test'
import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
const origin = process.env.LABS_ORIGIN ?? 'http://127.0.0.1:5187'

test('billboard rotates, pauses, validates copy, fits the workspace and respects reduced motion', { timeout: 60000 }, async () => {
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] })
  try {
    const context = await browser.newContext({ viewport: { width: 1600, height: 1100 } })
    const page = await context.newPage(), errors = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
    await page.clock.install({ time: new Date('2026-10-11T12:00:00Z') })
    await page.goto(`${origin}/experiments/flip-billboard`)
    const frame = page.locator('.a1-flip-billboard'), canvas = frame.locator('canvas')
    const heading = frame.getByRole('heading', { level: 1 })
    await expect(canvas).toBeVisible()
    await page.getByRole('button', { name: 'Pause headlines', exact: true }).click()
    await page.clock.pauseAt(new Date('2026-10-11T12:01:00Z'))
    await expect(heading).toHaveText('A1 Design by the rules')
    await page.getByRole('button', { name: 'Next headline' }).click()
    await page.clock.runFor(250)
    await expect(canvas).toHaveAttribute('data-flipping', 'true')
    await page.clock.runFor(4500)
    await expect(canvas).toHaveAttribute('data-flipping', 'false')
    await expect(heading).toHaveText('Small ideas. Big moves.')
    await page.clock.runFor(7000)
    await expect(heading).toHaveText('Small ideas. Big moves.')
    await page.getByRole('button', { name: 'Resume headlines', exact: true }).first().click()
    await page.clock.runFor(6200)
    await expect(heading).toHaveText('Your next starts here.')
    await page.getByRole('textbox', { name: 'Headline 1', exact: true }).fill('aa')
    await page.clock.runFor(4500)
    await page.getByRole('textbox', { name: 'Headline 1', exact: true }).fill('cz')
    await page.clock.runFor(120)
    await expect(canvas).toHaveAttribute('data-flipping', 'true')
    const intermediate = await canvas.getAttribute('data-characters')
    assert.equal(intermediate.trim()[0], 'c', 'a to c has already settled')
    assert.notEqual(intermediate.trim()[1], 'z', 'a to z is still cycling')
    await expect(canvas).toHaveAttribute('data-active-cards', '1')
    await page.screenshot({ path: '/tmp/billboard-cycling.png' })
    await page.clock.runFor(1000)
    await expect(canvas).toHaveAttribute('data-flipping', 'false')
    assert.equal((await canvas.getAttribute('data-characters')).trim(), 'cz')
    await page.getByRole('textbox', { name: 'Headline 1', exact: true }).fill('New ideas\nstart here.')
    await expect(heading).toHaveText('New ideas start here.')
    await page.getByRole('textbox', { name: 'Headline 1', exact: true }).fill('A headline that does not fit')
    await expect(page.getByText('Use up to 2 lines, with 12 characters per line.')).toBeVisible()
    await expect(heading).toHaveText('New ideas start here.')
    await page.getByRole('textbox', { name: 'Headline 1', exact: true }).fill('New ideas\nstart here.')
    await page.getByRole('button', { name: 'Resume headlines', exact: true }).first().click()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.getByRole('button', { name: 'Next headline' }).click()
    await page.clock.runFor(100)
    await expect(canvas).toHaveAttribute('data-flipping', 'false')
    const still = await heading.textContent()
    await page.clock.runFor(7000)
    await expect(heading).toHaveText(still)
    await expect(frame.getByRole('link')).toHaveCount(0)
    await expect(frame.getByRole('button')).toHaveCount(0)
    await expect(page.getByText('A1 Studio', { exact: true })).toHaveCount(0)
    await expect(page.getByText('Start small. Make it matter.', { exact: true })).toHaveCount(0)
    await page.clock.resume()
    await expect(page.locator('iframe')).toHaveCount(0)
    for (const width of [390, 600, 900, 1200, 1600]) {
      await page.setViewportSize({ width, height: 1100 })
      await expect(canvas).toBeVisible()
      await expect.poll(() => frame.locator('.a1-flip-billboard__stage').evaluate(stage => {
        const bounds = stage.getBoundingClientRect()
        return Math.abs(bounds.height - bounds.width / 3)
      })).toBeLessThan(1)
      await expect.poll(() => page.locator('body').evaluate(body => body.scrollWidth <= body.ownerDocument.defaultView.innerWidth)).toBe(true)
    }
    const results = await new AxeBuilder({ page }).include('.a1-flip-billboard').disableRules(['color-contrast']).analyze()
    assert.deepEqual(results.violations, [])
    await page.screenshot({ path: '/tmp/flip-billboard-dark.png' })
    for (const mode of ['light', 'dark', 'system']) {
      await page.evaluate(mode => localStorage.setItem('a1-labs-color-mode', mode), mode)
      await page.emulateMedia({ colorScheme: 'light' })
      await page.reload()
      await expect(frame.locator('.a1-flip-billboard__stage')).toHaveAttribute('data-stock', mode === 'dark' ? 'dark' : 'light')
      await expect(canvas).toBeVisible()
      if (mode === 'system') {
        await page.emulateMedia({ colorScheme: 'dark' })
        await expect(frame.locator('.a1-flip-billboard__stage')).toHaveAttribute('data-stock', 'dark')
        await page.emulateMedia({ colorScheme: 'light' })
        await expect(frame.locator('.a1-flip-billboard__stage')).toHaveAttribute('data-stock', 'light')
      }
    }
    await page.screenshot({ path: '/tmp/flip-billboard-light.png' })
    await canvas.evaluate(c => c.getContext('webgl2').getExtension('WEBGL_lose_context').loseContext())
    await expect(frame.getByText('The 3D display is unavailable.', { exact: false })).toBeVisible()
    await expect(heading).toBeVisible()
    assert.deepEqual(errors, [])
  } finally { await browser.close() }
})
