import test from 'node:test'
import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
const origin = process.env.LABS_ORIGIN ?? 'http://127.0.0.1:5187'

test('pagination types share full-data operations, respect boundaries and validate direct jumps', async () => {
  const browser = await chromium.launch()
  try {
    const context = await browser.newContext({ viewport: { width: 1600, height: 1100 } }), page = await context.newPage()
    page.setDefaultTimeout(10000)
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.goto(`${origin}/experiments/pagination-types`)
    await page.getByRole('slider', { name: 'Data set size', exact: true }).press('End')
    await page.getByRole('slider', { name: 'Data set size', exact: true }).press('ArrowLeft')
    const root = page.locator('.a1-pagination-types-lab')
    await expect(page.getByRole('radio', { name: 'A1 default', exact: true })).toBeChecked()
    await expect(root).toContainText('Showing 1–10 of 500 results')
    await expect(root.getByRole('button', { name: 'Previous page' })).toBeDisabled()
    await root.getByRole('button', { name: 'Next page' }).click()
    await expect(root).toContainText('Showing 11–20 of 500 results')
    for (const label of ['Compact', 'First and last', 'Page selector', 'Jump to page', 'Numbered with jump', 'A1 default']) {
      await page.getByRole('radio', { name: label, exact: true }).press('Space')
      await expect(root).toContainText('Showing 11–20 of 500 results')
      await expect(root.getByRole('navigation', { name: 'Pagination', exact: true })).toHaveCount(1)
    }
    await page.getByRole('radio', { name: 'First and last', exact: true }).press('Space')
    await root.getByRole('button', { name: 'Last page', exact: true }).click()
    await expect(root).toContainText('Showing 491–500 of 500 results')
    await expect(root.getByRole('button', { name: 'Next', exact: true })).toBeDisabled()
    await root.getByRole('button', { name: 'First page', exact: true }).click()
    await expect(root.getByRole('button', { name: 'Previous', exact: true })).toBeDisabled()
    await page.getByRole('radio', { name: 'Page selector', exact: true }).press('Space')
    await root.getByRole('combobox', { name: 'Page', exact: true }).selectOption('25')
    await expect(root).toContainText('Showing 241–250 of 500 results')
    await page.getByRole('radio', { name: 'Jump to page', exact: true }).press('Space')
    const jump = root.getByRole('spinbutton', { name: 'Go to page', exact: true })
    await jump.fill('51'); await root.getByRole('button', { name: 'Go', exact: true }).click()
    await expect(root.getByRole('alert')).toContainText('1 to 50')
    await expect(jump).toBeFocused()
    await expect(root).toContainText('Showing 241–250 of 500 results')
    await jump.fill('12.5'); await jump.press('Enter')
    await expect(jump).toHaveAttribute('aria-invalid', 'true')
    await jump.fill('42'); await jump.press('Enter')
    await expect(root).toContainText('Showing 411–420 of 500 results')
    await expect(root.getByRole('status')).toContainText('Page 42. Rows 411–420 of 500.')
    await root.getByRole('searchbox', { name: 'Search all fields', exact: true }).fill('REQ-00500')
    await expect(root.locator('.a1-data-table__desktop-row')).toHaveCount(1)
    await expect(root).toContainText('REQ-00500')
    await expect(root.getByRole('navigation', { name: 'Pagination', exact: true })).toHaveCount(0)
    await root.getByRole('searchbox', { name: 'Search all fields', exact: true }).fill('')
    await page.getByRole('slider', { name: 'Data set size', exact: true }).press('End')
    await jump.fill('100'); await jump.press('Enter')
    await expect(root).toContainText('Showing 991–1000 of 1000 results')
    await root.getByRole('combobox', { name: 'Rows per page' }).selectOption('100')
    await expect(root).toContainText('Showing 1–100 of 1000 results')
    await root.getByRole('combobox', { name: 'Rows per page' }).selectOption('10')
    await root.getByRole('columnheader', { name: 'Amount', exact: true }).getByRole('button').click()
    await expect(root.getByRole('columnheader', { name: 'Amount', exact: true })).toHaveAttribute('aria-sort', 'ascending')
    await page.getByRole('radio', { name: 'Above', exact: true }).click()
    assert.equal(await root.evaluate(el => Boolean(el.querySelector('.a1-data-table-footer').compareDocumentPosition(el.querySelector('table')) & Node.DOCUMENT_POSITION_FOLLOWING)), true)
    await page.getByRole('radio', { name: 'Below', exact: true }).click()
    assert.equal(await root.evaluate(el => Boolean(el.querySelector('.a1-data-table-footer').compareDocumentPosition(el.querySelector('table')) & Node.DOCUMENT_POSITION_FOLLOWING)), false)
    const axe = await new AxeBuilder({ page }).include('.a1-pagination-types-lab').disableRules(['color-contrast']).analyze()
    assert.deepEqual(axe.violations.map(item => item.id), [])
    for (const label of ['A1 default', 'Compact', 'First and last', 'Page selector', 'Jump to page', 'Numbered with jump']) {
      await page.getByRole('radio', { name: label, exact: true }).press('Space')
      await page.setViewportSize({ width: 390, height: 844 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), label)
      await expect(root.getByRole('navigation', { name: 'Pagination', exact: true })).toBeVisible()
      await page.setViewportSize({ width: 1600, height: 1100 })
    }
    await page.screenshot({ path: '/tmp/labs-pagination-types.png' })
    assert.deepEqual(errors, [])
  } finally { await browser.close() }
})
