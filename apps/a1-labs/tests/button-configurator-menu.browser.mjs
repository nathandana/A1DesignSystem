import assert from 'node:assert/strict'
import test from 'node:test'
import { chromium } from 'playwright'

const origin = process.env.LABS_ORIGIN ?? 'http://127.0.0.1:5187'

test('button opens and applies its configuration from an anchored menu', async t => {
  const browser = await chromium.launch({ headless: true })
  t.after(() => browser.close())
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  await page.goto(`${origin}/experiments/button-configurator-menu`)

  assert.equal(await page.locator('.a1-labs-configuration').count(), 1)
  const button = page.getByRole('button', { name: 'Save changes', exact: true })
  await button.click()
  const menu = page.getByRole('dialog', { name: 'Configure button' })
  await menu.waitFor()

  await menu.getByLabel('Label').fill('Create project')
  await menu.getByRole('radio', { name: 'Success' }).click()
  await menu.getByRole('radio', { name: 'Large' }).click()
  await menu.getByLabel('Icon', { exact: true }).selectOption('check')
  await menu.getByRole('radio', { name: 'End' }).click()

  const configured = page.getByRole('button', { name: 'Create project', exact: true })
  await configured.waitFor()
  assert.match(await configured.getAttribute('class'), /a1-button--success/)
  assert.match(await configured.getAttribute('class'), /a1-button--lg/)
  assert.equal(await configured.locator('.a1-button__icon').textContent(), 'check')
  await page.waitForTimeout(50)
  const buttonBox = await configured.boundingBox()
  const menuBox = await menu.boundingBox()
  assert.ok(menuBox.x >= buttonBox.x + buttonBox.width || menuBox.x + menuBox.width <= buttonBox.x)

  await page.keyboard.press('Escape')
  await menu.waitFor({ state: 'hidden' })

  await page.locator('.a1-labs-configuration').getByRole('radio', { name: /Toolbar/ }).check({ force: true })
  await configured.click()
  const toolbar = page.getByRole('toolbar', { name: 'Button configuration' })
  await toolbar.waitFor()
  const trigger = page.locator('[data-configurator-trigger="true"]')
  await toolbar.getByRole('textbox', { name: 'Label' }).fill('Toolbar label')
  await page.getByRole('button', { name: 'Toolbar label', exact: true }).waitFor()
  await toolbar.getByRole('button', { name: 'Variant' }).click()
  await page.getByRole('dialog', { name: 'Variant' }).getByRole('button', { name: 'Destructive' }).click()
  assert.match(await trigger.getAttribute('class'), /a1-button--destructive/)

  await page.keyboard.press('Escape')
  await page.locator('.a1-labs-configuration').getByRole('radio', { name: /Extended toolbar/ }).check({ force: true })
  await trigger.click()
  const extendedToolbar = page.getByRole('toolbar', { name: 'Extended button configuration' })
  await extendedToolbar.waitFor()
  await extendedToolbar.getByRole('radio', { name: 'Success' }).click()
  assert.match(await trigger.getAttribute('class'), /a1-button--success/)
  await extendedToolbar.getByRole('button', { name: 'Decrease size' }).click()
  assert.doesNotMatch(await trigger.getAttribute('class'), /a1-button--lg/)
  await extendedToolbar.getByRole('button', { name: 'Increase size' }).click()
  assert.match(await trigger.getAttribute('class'), /a1-button--lg/)

  await page.keyboard.press('Escape')
  await page.locator('.a1-labs-configuration').getByRole('radio', { name: /Context menu/ }).check({ force: true })
  const contextTrigger = page.locator('[data-context-trigger="true"]')
  const contextTriggerBox = await contextTrigger.boundingBox()
  await contextTrigger.click({ button: 'right', position: { x: 8, y: 8 } })
  const contextMenu = page.getByRole('menu', { name: 'Configure button' })
  await contextMenu.waitFor()
  assert.equal(await contextMenu.evaluate(element => !element.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, cancelable: true }))), true)
  assert.equal(await page.evaluate(() => !document.body.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, cancelable: true }))), true)
  const contextMenuBox = await contextMenu.boundingBox()
  assert.ok(Math.abs(contextMenuBox.x - (contextTriggerBox.x + 8)) <= 2)
  assert.ok(Math.abs(contextMenuBox.y - (contextTriggerBox.y + 12)) <= 2)
  assert.equal(await contextMenu.getByRole('menuitem', { name: /^Label/ }).count(), 0)
  assert.equal(await contextMenu.getByRole('menuitem', { name: /Full width.*Off/ }).count(), 1)
  await contextMenu.getByRole('menuitem', { name: /Full width.*Off/ }).click()
  assert.equal(await contextMenu.getByRole('menuitem', { name: /Full width.*On/ }).count(), 1)
  assert.equal(await contextMenu.getByRole('menuitem', { name: /Button states/ }).count(), 0)
  await contextMenu.getByRole('menuitem', { name: /Disabled.*Off/ }).click()
  await page.keyboard.press('Escape')
  await contextTrigger.click({ button: 'right' })
  await contextMenu.waitFor()
  assert.equal(await contextMenu.getByRole('menuitem', { name: /Disabled.*On/ }).count(), 1)
  await contextMenu.getByRole('menuitem', { name: /Disabled.*On/ }).click()
  await page.keyboard.press('Escape')
  const inlineLabel = trigger.getByRole('textbox', { name: 'Edit button label' })
  assert.equal(await inlineLabel.getAttribute('contenteditable'), 'false')
  await inlineLabel.dblclick()
  await inlineLabel.fill('Context label')
  assert.equal(await inlineLabel.getAttribute('contenteditable'), 'true')
  await page.keyboard.press('Escape')
  await contextTrigger.click({ button: 'right' })
  await contextMenu.getByRole('menuitem', { name: /^Size/ }).hover()
  const sizeFlyout = page.getByRole('menu', { name: 'Button size' })
  await page.waitForTimeout(100)
  assert.equal(await sizeFlyout.count(), 0)
  await sizeFlyout.waitFor()
  const parentBox = await contextMenu.boundingBox()
  const sizeItemBox = await contextMenu.getByRole('menuitem', { name: /^Size/ }).boundingBox()
  const sizeFlyoutBox = await sizeFlyout.boundingBox()
  assert.ok(Math.abs(sizeFlyoutBox.x - parentBox.x - parentBox.width) <= 8)
  assert.ok(Math.abs(sizeFlyoutBox.y - sizeItemBox.y) <= 2)
  await contextMenu.waitFor()
  assert.equal(await contextMenu.isVisible(), true)
  await sizeFlyout.getByRole('menuitem', { name: 'Small' }).click()
  assert.equal(await contextMenu.isVisible(), true)
  assert.match(await trigger.getAttribute('class'), /a1-button--sm/)

  assert.equal(await contextMenu.getByRole('menuitem', { name: /^Label/ }).count(), 0)
  await page.keyboard.press('Escape')
  await page.locator('.a1-labs-configuration').getByRole('radio', { name: /Consolidated context menu/ }).check({ force: true })
  await contextTrigger.click({ button: 'right' })
  await contextMenu.waitFor()
  assert.equal(await contextMenu.getByRole('menuitem', { name: /^Size/ }).count(), 0)
  const consolidatedSize = contextMenu.getByRole('toolbar', { name: 'Size' })
  await consolidatedSize.getByRole('radio', { name: 'Default' }).click()
  assert.doesNotMatch(await trigger.getAttribute('class'), /a1-button--sm|a1-button--lg/)
  const consolidatedPosition = contextMenu.getByRole('toolbar', { name: 'Icon position' })
  await consolidatedPosition.getByRole('radio', { name: 'Start' }).click()
  assert.equal(await consolidatedPosition.getByRole('radio', { name: 'Start' }).getAttribute('aria-checked'), 'true')
  await page.keyboard.press('Escape')
  await page.locator('.a1-labs-configuration').getByRole('radio', { name: /^Toolbar/ }).check({ force: true })
  await page.setViewportSize({ width: 360, height: 760 })
  await trigger.click()
  await toolbar.waitFor()
  assert.equal(await toolbar.getByRole('button', { name: 'Variant' }).isVisible(), true)
  assert.equal(await toolbar.getByRole('button', { name: 'More tools' }).isVisible(), true)
})
