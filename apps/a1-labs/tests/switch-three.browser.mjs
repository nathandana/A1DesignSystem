import test from 'node:test'
import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
const origin = process.env.LABS_ORIGIN ?? 'http://127.0.0.1:5187'
test('3D switch reverses, keeps native semantics, follows themes and falls back accessibly', async () => {
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage(), errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(`${origin}/experiments/switch-three`)
    const control = page.getByRole('switch', { name: 'Switch', exact: true }), root = page.locator('.a1-switch-three'), canvas = root.locator('canvas')
    await expect(canvas).toBeVisible(); await expect(root).toHaveAttribute('data-fallback', 'false')
    await expect(control).not.toBeChecked()
    await control.press('Space'); await expect(control).toBeChecked()
    await expect(canvas).toHaveAttribute('data-moving', 'false')
    await page.screenshot({ path: '/tmp/switch-three-on.png' })
    await page.getByRole('slider', { name: 'Transition duration (ms)' }).press('End')
    await control.press('Space'); await expect(canvas).toHaveAttribute('data-moving', 'true')
    await control.press('Space'); await expect(control).toBeChecked()
    await expect(canvas).toHaveAttribute('data-moving', 'false')
    await control.press('Space'); await page.emulateMedia({ reducedMotion: 'reduce' })
    await expect(canvas).toHaveAttribute('data-moving', 'false'); await expect(control).not.toBeChecked()
    await page.getByRole('switch', { name: 'Disabled', exact: true }).press('Space')
    await expect(control).toBeDisabled()
    await page.getByRole('switch', { name: 'Disabled', exact: true }).press('Space')
    await page.getByRole('slider', { name: 'Scale', exact: true }).press('Home')
    await expect.poll(() => root.locator('.a1-switch-three__surface').evaluate(e => e.getBoundingClientRect().width)).toBe(40)
    await control.press('Space'); await expect(control).toBeChecked()
    await page.getByRole('slider', { name: 'Scale', exact: true }).press('End')
    await control.press('Space')
    await expect(control).not.toBeChecked()
    const darkSurface = await canvas.screenshot()
    await page.evaluate(() => document.documentElement.classList.replace('a1-theme-dark', 'a1-theme-light'))
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    assert.notDeepEqual(await canvas.screenshot(), darkSurface, 'renderer repaints the live mode palette')
    await control.press('Space')
    await page.screenshot({ path: '/tmp/switch-three-light.png' })
    await page.emulateMedia({ forcedColors: 'active' })
    await expect(root).toHaveAttribute('data-fallback', 'true')
    await expect(root.locator('.a1-switch-three__fallback')).toBeVisible()
    await control.press('Space'); await expect(control).not.toBeChecked()
    await page.emulateMedia({ forcedColors: 'none' })
    await expect(canvas).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    assert.ok(await root.evaluate(e => e.getBoundingClientRect().right <= innerWidth))
    await page.screenshot({ path: '/tmp/switch-three-phone.png' })
    const results = await new AxeBuilder({ page }).include('.a1-switch-three').disableRules(['color-contrast']).analyze()
    assert.deepEqual(results.violations, [])
    await canvas.evaluate(c => c.getContext('webgl2').getExtension('WEBGL_lose_context').loseContext())
    await expect(root).toHaveAttribute('data-fallback', 'true')
    await control.press('Space'); await expect(control).toBeChecked()
    assert.deepEqual(errors, [])
  } finally { await browser.close() }
})
