import test from 'node:test'
import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
import { createDataset } from '../src/sample-data/datasets.js'
const inventory = createDataset('inventory', 50)
const origin = process.env.LABS_ORIGIN ?? 'http://127.0.0.1:5187'

test('table pagination placement preserves the page and works with data configurations', async () => {
  const browser = await chromium.launch()
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
    page.setDefaultTimeout(10000)
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.goto(`${origin}/experiments/data-tables`)
    await page.getByRole('slider', { name: 'Data set size', exact: true }).press('ArrowLeft')
    await expect(page.getByRole('switch', { name: 'Row selection' })).toHaveCount(0)
    const root = page.locator('.a1-data-tables-lab')
    const pager = root.getByRole('navigation', { name: 'Pagination', exact: true })
    await expect(pager).toHaveClass(/a1-pagination--md/)
    await page.getByRole('radiogroup', { name: 'Pagination size' }).getByRole('radio', { name: 'Small', exact: true }).press('Space')
    await expect(pager).toHaveClass(/a1-pagination--sm/)
    await page.getByRole('radiogroup', { name: 'Pagination size' }).getByRole('radio', { name: 'Medium', exact: true }).press('Space')
    await expect(pager).toHaveClass(/a1-pagination--md/)
    await expect(pager).toHaveCount(1)
    await expect(root.locator('.a1-data-table__desktop-row')).toHaveCount(10)
    await pager.getByRole('button', { name: 'Next page' }).click()
    await expect(root).toContainText('Showing 11–20 of 50 results')
    const placement = () => root.evaluate(el => {
      const table = el.querySelector('.a1-data-table-scroll'), footer = el.querySelector('.a1-data-table-footer')
      return Boolean(footer.compareDocumentPosition(table) & Node.DOCUMENT_POSITION_FOLLOWING)
    })
    assert.equal(await placement(), false)
    await page.getByRole('radio', { name: 'Above', exact: true }).press('Space')
    assert.equal(await placement(), true)
    await expect(root).toContainText('Showing 11–20 of 50 results')
    await page.getByRole('radio', { name: 'Inline', exact: true }).click()
    const inline = root.locator('.a1-data-table-inline-pagination')
    const geometry = () => inline.evaluate(el => {
      const filters = el.querySelector('.a1-dt-filters').getBoundingClientRect()
      const controls = el.querySelector('.a1-data-table-footer__controls').getBoundingClientRect()
      return { filtersBottom: filters.bottom, controlsTop: controls.top, controlsBottom: controls.bottom }
    })
    const wide = await geometry()
    assert.equal(wide.filtersBottom, wide.controlsBottom)
    await expect(root).toContainText('Showing 11–20 of 50 results')
    for (const width of [1100, 390]) {
      await page.setViewportSize({ width, height: 1000 })
      const narrow = await geometry()
      assert.ok(narrow.controlsTop > narrow.filtersBottom)
      await expect(pager).toHaveCount(1)
      await expect(root).toContainText('Showing 11–20 of 50 results')
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    }
    await page.setViewportSize({ width: 1600, height: 1000 })
    await root.getByRole('combobox', { name: 'Rows per page' }).selectOption('7')
    await expect(root.getByRole('combobox', { name: 'Rows per page' })).toHaveValue('7')
    await expect(root.locator('.a1-data-table__desktop-row')).toHaveCount(7)
    await root.locator('.a1-dt-filters__chips').getByRole('button', { name: 'Status', exact: true }).click()
    await page.getByRole('dialog', { name: 'Status', exact: true }).getByRole('button', { name: 'Out of stock', exact: true }).click()
    await page.keyboard.press('Escape')
    await expect(root.locator('.a1-data-table__desktop-row')).toHaveCount(inventory.filter(row => row.stock === 0).length)
    await root.getByRole('button', { name: 'Clear all', exact: true }).click()
    await root.getByRole('combobox', { name: 'Rows per page' }).selectOption('25')
    await expect(root.locator('.a1-data-table__desktop-row')).toHaveCount(25)
    await expect(root).toContainText('Showing 1–25 of 50 results')
    await root.getByRole('combobox', { name: 'Rows per page' }).selectOption('5')
    await expect(root.getByRole('combobox', { name: 'Rows per page' })).toHaveValue('5')
    await pager.getByRole('button', { name: 'Page 10', exact: true }).click()
    await expect(pager.getByRole('button', { name: 'Next page' })).toBeDisabled()
    await expect(root).toContainText('Showing 46–50 of 50 results')
    // Sorting and searching operate on the full set, not just the current page.
    await root.getByRole('columnheader', { name: 'Price' }).getByRole('button').click()
    await expect(root.getByRole('columnheader', { name: 'Price' })).toHaveAttribute('aria-sort', 'ascending')
    await root.getByRole('searchbox', { name: 'Search all fields', exact: true }).fill(inventory[0].sku)
    await expect(root.locator('.a1-data-table__desktop-row')).toHaveCount(1)
    await expect(root).toContainText(inventory[0].sku)
    await page.getByRole('radio', { name: 'Team directory', exact: true }).press('Space')
    await expect(root).toContainText('Alex Morgan')
    await page.getByRole('radio', { name: 'Invoices', exact: true }).press('Space')
    await expect(root).toContainText('INV-1001')
    await page.getByRole('radio', { name: '8', exact: true }).press('Space')
    await expect(root.getByRole('columnheader')).toHaveCount(8)
    const count = page.getByRole('slider', { name: 'Data set size', exact: true })
    await count.press('Home')
    await expect(count).toHaveAttribute('aria-valuetext', '7 rows')
    await expect(root).toContainText('of 7 results')
    await count.press('ArrowRight')
    await expect(count).toHaveAttribute('aria-valuetext', '10 rows')
    await count.press('ArrowRight')
    await expect(count).toHaveAttribute('aria-valuetext', '25 rows')
    await count.press('End')
    await expect(count).toHaveAttribute('aria-valuetext', '1,000 rows')
    await page.getByRole('radio', { name: 'Compact', exact: true }).click()
    await expect(page.getByRole('combobox', { name: 'Rows on each page' })).toHaveCount(0)
    await expect(page.getByRole('group', { name: 'Narrow screens', exact: true })).toHaveCount(0)
    await page.setViewportSize({ width: 390, height: 844 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await expect(pager).toBeVisible()
    await pager.getByRole('button', { name: 'Next page' }).click()
    await expect(root).toContainText('Showing 6–10 of 1000 results')
    await expect(root.locator('.a1-data-table__mobile-card').first()).toBeVisible()
    assert.deepEqual(errors, [])
  } finally { await browser.close() }
})

test('both places duplicate, synchronized pagination above and below the table', async () => {
  const browser = await chromium.launch()
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
    page.setDefaultTimeout(10000)
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.goto(`${origin}/experiments/data-tables`)
    await page.getByRole('slider', { name: 'Data set size', exact: true }).press('ArrowLeft')
    const root = page.locator('.a1-data-tables-lab')
    await page.getByRole('radio', { name: 'Both', exact: true }).press('Space')
    const above = root.getByRole('navigation', { name: 'Pagination above table', exact: true })
    const below = root.getByRole('navigation', { name: 'Pagination below table', exact: true })
    await expect(above).toHaveCount(1); await expect(below).toHaveCount(1)
    await expect(root.getByRole('navigation', { name: 'Pagination', exact: true })).toHaveCount(0)
    // One footer before the table and one after it.
    const order = await root.evaluate(el => {
      const table = el.querySelector('.a1-data-table-scroll')
      return [...el.querySelectorAll('.a1-data-table-footer')].map(footer =>
        footer.compareDocumentPosition(table) & Node.DOCUMENT_POSITION_FOLLOWING ? 'above' : 'below')
    })
    assert.deepEqual(order, ['above', 'below'])
    // Either copy drives the same state, and both reflect it.
    await below.getByRole('button', { name: 'Next page' }).click()
    await expect(root.getByText('Showing 11–20 of 50 results')).toHaveCount(2)
    await expect(above.getByRole('button', { name: 'Page 2', exact: true })).toHaveAttribute('aria-current', 'page')
    await above.getByRole('button', { name: 'Next page' }).click()
    await expect(below.getByRole('button', { name: 'Page 3', exact: true })).toHaveAttribute('aria-current', 'page')
    const perPage = root.getByRole('combobox', { name: 'Rows per page' })
    await expect(perPage).toHaveCount(2)
    await perPage.first().selectOption('25')
    await expect(perPage.last()).toHaveValue('25')
    await expect(root.locator('.a1-data-table__desktop-row')).toHaveCount(25)
    await page.setViewportSize({ width: 390, height: 844 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await expect(above).toBeVisible(); await expect(below).toBeAttached()
    assert.deepEqual(errors, [])
  } finally { await browser.close() }
})
