export const categoryTreeId = category => `category-${category}`

// Shared search vocabulary for the gallery and sidebar. Tags are curated
// synonyms, independent of governed type filter IDs. Every query term must match.
export function matchesExperiment(item, search = '') {
  const terms = search.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean)
  const category = experimentCategories.find(value => value.id === item.category)?.label ?? item.category
  const types = item.types.map(id => experimentTypes.find(value => value.id === id)?.label ?? id)
  const text = [item.title, item.description, category, ...types, ...(item.tags ?? [])].join(' ').toLocaleLowerCase()
  return terms.every(term => text.includes(term))
}

const byName = new Intl.Collator('en', { sensitivity: 'base', numeric: true })

// Sidebar tree: categories and their experiments both sorted by name.
export function experimentTree(search = '') {
  return experimentCategories.map(category => ({
    id: categoryTreeId(category.id),
    label: category.label,
    icon: category.icon,
    children: experiments
      .filter(item => item.category === category.id && matchesExperiment(item, search))
      .map(item => ({ id: item.id, label: item.title, href: item.href, icon: item.icon }))
      .sort((a, b) => byName.compare(a.label, b.label)),
  }))
    .filter(category => category.children.length > 0)
    .sort((a, b) => byName.compare(a.label, b.label))
}
