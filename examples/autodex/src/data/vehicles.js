export function getVehicleById(id) {
  return vehicleById[id] ?? null;
}

export function getRelatedVehicles(vehicle) {
  if (!vehicle?.relatedIds) return [];
  return vehicle.relatedIds.map((id) => vehicleById[id]).filter(Boolean);
}

export function getFeaturedVehicles() {
  return [
    vehicleById["1990-mazda-miata-se"],
    vehicleById["1973-porsche-911-carrera-rs"],
    vehicleById["2020-tesla-model-3-performance"],
    vehicleById["2019-porsche-911-gt3-rs"],
  ].filter(Boolean);
}

export function getVehiclesByEra(eraId) {
  return vehicles.filter((v) => v.era === eraId);
}

export function getVehiclesByMake(make) {
  return vehicles.filter((v) => v.make === make);
}

